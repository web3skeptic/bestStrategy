// Writes src/aiGenomes.ts — the genome each difficulty plays with — from
// evolved genome files (only the levels given are replaced).
//
//   npx tsx ai-evolve/export.ts --hard=ai-evolve/out/hard-b/best.json --medium=... --easy=...
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { normalizeGenome, type AiGenome } from '../src/aiGenome';

const args: Record<string, string> = {};
for (const a of process.argv.slice(2)) { const m = a.match(/^--([^=]+)=(.*)$/); if (m) args[m[1]!] = m[2]!; }

const OUT = fileURLToPath(new URL('../src/aiGenomes.ts', import.meta.url));
const LEVELS = ['easy', 'medium', 'hard'] as const;
const round = (_k: string, v: unknown) => typeof v === 'number' ? Math.round(v * 1000) / 1000 : v;

async function main(): Promise<void> {
  // Keep whatever is already exported for levels not being replaced.
  const current: Partial<Record<typeof LEVELS[number], AiGenome>> = {};
  if (existsSync(OUT)) {
    const mod = await import('../src/aiGenomes');
    for (const l of LEVELS) current[l] = mod.LEVEL_GENOMES[l];
  }
  const sources: string[] = [];
  for (const l of LEVELS) {
    if (args[l]) {
      current[l] = normalizeGenome(JSON.parse(readFileSync(args[l]!, 'utf8')));
      sources.push(`${l}: ${args[l]}`);
    }
    if (!current[l]) throw new Error(`no genome for ${l} (pass --${l}=<file>)`);
  }
  writeFileSync(OUT, `// GENERATED by ai-evolve/export.ts — the genome each AI difficulty plays
// with (see src/aiGenome.ts for what every gene means and ai-evolve/README.md
// for how they were evolved). Regenerate rather than hand-editing.
import type { AiGenome } from './aiGenome';

export const LEVEL_GENOMES: Record<'easy' | 'medium' | 'hard', AiGenome> = ${JSON.stringify(current, round, 2)};
`);
  console.log(`wrote ${OUT}${sources.length ? ` (${sources.join(', ')})` : ''}`);
}

main();
